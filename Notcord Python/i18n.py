class I18nManager:
    """Manages internationalization state and translation retrieval for 5 languages."""
    LANG_DISPLAY_MAP = {
        "en": "🌐 English",
        "tr": "🌐 Türkçe",
        "es": "🌐 Español",
        "pt": "🌐 Português",
        "ru": "🌐 Русский"
    }

    DISPLAY_TO_CODE = {v: k for k, v in LANG_DISPLAY_MAP.items()}

    def __init__(self, default_lang="en"):
        self.current_lang = default_lang if default_lang in TRANSLATIONS else "en"
        self._listeners = []

    def set_language(self, lang_code: str):
        if lang_code in TRANSLATIONS:
            self.current_lang = lang_code
            for cb in self._listeners:
                try:
                    cb(self.current_lang)
                except Exception:
                    pass

    def add_listener(self, callback):
        if callback not in self._listeners:
            self._listeners.append(callback)

    def t(self, key: str, **kwargs) -> str:
        text = TRANSLATIONS.get(self.current_lang, {}).get(key)
        if text is None:
            text = TRANSLATIONS.get("en", {}).get(key, key)
        if kwargs:
            try:
                return text.format(**kwargs)
            except Exception:
                return text
        return text

    def get_supported_languages(self):
        return list(self.LANG_DISPLAY_MAP.values())

    def get_display_name(self, code: str) -> str:
        return self.LANG_DISPLAY_MAP.get(code, "🌐 English")

    def get_code_from_display(self, display: str) -> str:
        return self.DISPLAY_TO_CODE.get(display, "en")


